#!/usr/bin/env python3
"""Produce deterministic, SHA256 CSP-pinned, gzipped GW006 browser C asset.

Source-only build; this does NOT enable TLS, board flash or hardware GPIO.
"""
import argparse
import base64
import gzip
import hashlib
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
TARGET=ROOT/"firmware/core/gwir_dashboard_asset.c"

def assemble():
    html=(ROOT/"web/gw006_remote.html").read_text(encoding="utf-8")
    protocol=(ROOT/"web/gw006_protocol.mjs").read_text(encoding="utf-8")
    ui=(ROOT/"web/gw006_remote_ui.js").read_text(encoding="utf-8")
    slot="<script>/*GWIR_INLINE_SCRIPT*/</script>"
    if html.count(slot)!=1:
        raise ValueError("HTML must have exactly one internal script slot")
    if re.search(r"(?m)^\s*import\s", protocol+"\n"+ui):
        raise ValueError("External scripts forbidden")
    protocol,removed=re.subn(r"\bexport\s+\{[^}]+\};?\s*$","",protocol,
                              count=1,flags=re.S)
    if removed!=1 or re.search(r"\bexport\b",protocol):
        raise ValueError("Unexpected ES module exports")
    js=protocol.rstrip()+"\n"+ui.rstrip()+"\n"
    if any(name in js for name in
           ("localStorage.", "localStorage[", "sessionStorage.", "sessionStorage[")):
        raise ValueError("Browser-side secret persistence forbidden")
    html=html.replace("/*GWIR_INLINE_SCRIPT*/",js,1)
    styles=re.findall(r"<style>(.*?)</style>",html,flags=re.S)
    scripts=re.findall(r"<script>(.*?)</script>",html,flags=re.S)
    if len(styles)!=1 or len(scripts)!=1:
        raise ValueError("Unexpected execution points")
    if "<script src=" in html or "http://cdn" in html or "new Function(" in html:
        raise ValueError("External script execution forbidden")
    def sha_tag(value):
        h=hashlib.sha256(value.encode("utf-8")).digest()
        return "'sha256-"+base64.b64encode(h).decode("ascii")+"'"
    csp=("default-src 'none'; base-uri 'none'; form-action 'none'; "
         "frame-ancestors 'none'; object-src 'none'; "
         f"script-src {sha_tag(scripts[0])}; "
         f"style-src {sha_tag(styles[0])}; "
         "connect-src 'self'; img-src 'none'")
    plain=html.encode("utf-8")
    packed=gzip.compress(plain,compresslevel=9,mtime=0)
    if gzip.decompress(packed)!=plain:
        raise ValueError("gzip mismatch")
    if len(plain)>160000 or len(packed)>60000:
        raise ValueError("Embedded asset too large")
    return plain,packed,csp

def as_c(packed,csp):
    lines=[
        "/* Generated by build_gw006_browser_asset.py. No hardware activation. */",
        '#include "gwir_dashboard_asset.h"',
        "const uint8_t gwir_dashboard_gzip_html[] = {"
    ]
    for i in range(0,len(packed),24):
        lines.append("    "+",".join("0x%02x"%v for v in packed[i:i+24])+",")
    lines += ["};",
              "const size_t gwir_dashboard_gzip_len = sizeof(gwir_dashboard_gzip_html);",
              'const char gwir_dashboard_csp[] = "'+csp+'";',
              ""]
    return "\n".join(lines)

def main():
    parser=argparse.ArgumentParser()
    group=parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check",action="store_true")
    group.add_argument("--write",action="store_true")
    args=parser.parse_args()
    plain,packed,csp=assemble()
    if args.write:
        if not TARGET.is_file():
            raise ValueError("Extract pinned SDK bundle before embedding")
        TARGET.write_text(as_c(packed,csp),encoding="utf-8")
    print("GW006_BROWSER_ASSET=PASS",
          len(plain),"bytes",len(packed),"gz",
          "sha256="+hashlib.sha256(plain).hexdigest(),
          "NO_HARDWARE_NO_FLASH")

if __name__=="__main__":
    main()
